import { existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import reposGen from '../../data/gen/repos.json';
import evidenceGen from '../../data/gen/evidence.json';
import flowsGen from '../../data/gen/flows.json';
import config from '../../data/repos.config.json';

export type Quality = 'solid' | 'naive' | 'missing';
export interface Repo {
  slug: string; chip: string; name: string; family: string; hue: string; familyName: string;
  github: string; role: string | null; product: string; stack: string[]; architecture: string;
  components: { name: string; path: string; tech: string }[]; share: string; uncovered: string[];
}
export interface Evidence {
  id: string; repo: string; chapter: number; conceptId: string; section: string; concept: string;
  layer: string; file: string; branch: string | null; lines: [number, number] | null;
  shownFrom: number | null; numbered: boolean; snippet: string; what: string; quality: Quality;
  lesson: string; author: 'mine' | 'team' | 'unknown'; url: string; sha: string;
}
export interface Flow { id: string; repo: string; name: string; chapters: number[]; steps: string[] }

// The public edition is generated by scripts/build-public.mjs from redacted sources; nothing is filtered here.
export const repos = reposGen as Repo[];
export const evidence = evidenceGen as Evidence[];
export const flows = flowsGen as Flow[];
export const repoBySlug = Object.fromEntries(repos.map((r) => [r.slug, r]));
export const repoOrder = Object.fromEntries(repos.map((r, i) => [r.slug, i]));

const QUALITY_RANK: Record<Quality, number> = { solid: 0, naive: 1, missing: 2 };
export const qualityGlyph: Record<Quality, string> = { solid: '●', naive: '◐', missing: '○' };

/** Sort: solid first, then by repo order, so the best example leads. */
export const byStrength = (a: Evidence, b: Evidence) =>
  QUALITY_RANK[a.quality] - QUALITY_RANK[b.quality] || repoOrder[a.repo] - repoOrder[b.repo];

export function evidenceForChapter(order: number) {
  return evidence.filter((e) => e.chapter === order);
}

/** vscode:// link when the repo exists on this machine (main branch only). Dev server only: useless on a host. */
export function localLink(e: Evidence): string | null {
  if (!import.meta.env.DEV) return null;
  const r = config.repos.find((x) => x.slug === e.repo);
  if (!r?.local || e.branch) return null;
  const abs = join(r.local.replace(/^~/, homedir()), e.file);
  return existsSync(abs) ? `vscode://file${abs}${e.lines ? `:${e.lines[0]}` : ''}` : null;
}
